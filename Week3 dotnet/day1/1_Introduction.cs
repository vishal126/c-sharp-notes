// What is ASP.NET MVC?
// The ASP.NET MVC is a web application development framework provided by Microsoft which is built on top of the .NET Framework.

// It provide a clean separation of code

// The ASP.NET MVC Framework is based on MVC (Model-View-Controller) Design Pattern.
// ASP.NET MVC is a Framework whereas MVC is a Design Pattern.

// What is MVC?
// MVC  is an architectural software design pattern that is used for developing interactive applications where their user interaction is involved and based on the user interaction some event handling has occurred.
// MVC design pattern was introduced in the 1970s that basically divides an application into 3 major components as Model, View, and Controller.
// The main objective of the MVC design pattern is the separation of concerns (codes), which means the domain model and business logic are separated from the user interface (i.e. view).
// maintenance and testing of the application become simpler and easier.


// How does the MVC Design Pattern work in ASP.NET MVC Application?
// Let’s say we want to display the student details on a web page.

// So, when the client (user) issues a request something like “http://dotnettutorials.net/student/details/2” from a web browser then the request is handled by the MVC framework.

// Client <--(req/res)--> Controller
//                         |      |
//                         \/     \/
//                      View -> Model  <---> Database

// The controller is the component in the ASP.NET MVC application that actually receives the incoming HTTP request and then handles that request.

// In order to handle the incoming HTTP request, the controller does several things as follows:
// 1. The controller creates the model object that is required by a view.
//    The model is the component in the MVC design pattern that contains a set of classes to represent the domain data or business data as well as logic to manage the data.
// 2. The controller then selects a view to render the domain data or business data. The point is that, while selecting a view, it is the responsibility of the controller to pass the model data.
// 3. In the MVC Design Pattern, the one and only responsibility of a view is to display the model data. So, the responsibility of a view is to generate the necessary HTML which will render the model data or business data. Once the HTML is generated by the view, then that HTML is then sent to the client via the controller who initially made the request.



