// Why do we need Partial Views in the ASP.NET MVC Application? or When Should I Use Partial Views?
// We need to develop a partial view when we need a common part of the user interface on multiple pages in a web application.

// A partial view is a regular view that can be used multiple times in an application and has the file extension .cshtml.

// Sometimes we also use a partial view to divide a web page into small parts such as header, footer, and menu on Layout.

// Other examples are comments on the blogging site, shipping and billing address in the invoice on an e-commerce site, etc


// What are Partial Views in MVC Application?
// The Partial Views in ASP.NET MVC Application are the views that are rendered within another view.
// The HTML output generated by the partial view is rendered into the calling (or parent) view. Like views, partial views use the .cshtml file extension.


