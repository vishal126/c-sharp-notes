// Entity Framework
// It is a ORM (object relational mapping).
// Object-relational mapping in computer science is a programming technique for converting data between incompatible type systems using object-oriented programming languages. This creates, in effect, a "virtual object database" that can be used from within the programming language

// Being an ORM,  Entity Framework is a data access framework provided by Microsoft that helps to establish a relation between objects and data structure in the application.
// It is built over traditional ADO.NET and acts as a wrapper over ADO.NET and is an enhancement over ADO.NET that provides the data access in a more automated way
// thereby, reducing a developer’s effort to struggle with connections, data readers, or datasets.
// A developer can leverage Entity framework along with LINQ capabilities to write an optimized query to perform DB operations.
// The SQL or DB query execution would be handled by Entity Framework in the background and it will take care of all the transactions and concurrency issues that may occur.


// Entity Framework Approaches:
// 1. Model First,
// 2. Database First, and
// 3. Code First

// Generate database from the data model classes.
// Generate data model classes from an existing database


// The Model-First approach says that we have a model with all kinds of entities and relations/associations
// using which we can generate a database that will eventually have entities and properties converted into database tables
// and the columns and associations and relations would be converted into foreign keys respectively.

// The Database-First approach says that we already have an existing database and we need to access that database in our application.
// We can create an entity data model along with its relationship directly from the database
// All the entities, i.e., classes, would be generated by EF that could be used in the application's data access layer to participate in DB operation queries.

// The Code-First approach is the recommended approach with EF, especially when you are starting the development of an application from scratch.
// You can define the POCO classes in advance and their relationships and envision how your database structure and data model may look like by just defining the structure in the code.
// Entity Framework, at last, will take all the responsibility to generate a database for you for your POCO classes and for the data model and will take care of transactions, history, and migrations.


// 1. Model First
// A developer may not need to write any code for generating a database.
// EF provides the designer tools that could help you make a model and then generate a database.
// Model designer, when good to go, will help you to generate DDL commands that could be directly executed from Visual Studio or on your database server to create a database out of your created model.
// This creates an **EDMX file** that stores the information of your conceptual model, storage model, and mapping between both.
// The only drawback that I can see is that dropping the database completely and recreating it would be a challenge with this approach.

// 2. Database First
// we use it when we already have an existing database and need to access that in our application.
// Establishing the data access methodology for existing database with Entity Framework will help us to generate the context and classes in our solution through which we can access the database.
// Here, a model is created via a database and we have full control to choose what tables to include in the model, and what stored procedures, functions, or views to include.
// Whenever the database schema changes, you can easily update the entity data model.

// 3. Code First
// using this, a developer’s focus is only on the code and not on the database or data model.
// The developer can define classes and their mapping in the code itself and since now Entity Framework supports inheritance, it is easier to define relationships.
// EF takes care of creating or re-creating the database
// while creating a database, you can provide seed data, i.e., the master data that you want your tables to have when the database is created
// it may not create an EDMX file.
// we would have more control over the database since you are the one who created classes and relationships and managing it.